# data/node-schedule.json: the release schedule of Node.js, the start, LTS and end
# date of every major line, from schedule.json of nodejs/Release. A line that
# never became LTS has no lts. The lines before 4 (v0.x) are left out: no
# engines.node names them as a major.

import json
import re
import sys

import common

REPO = 'https://github.com/nodejs/Release'
RAW = 'https://raw.githubusercontent.com/nodejs/Release'

ABOUT = ('The release schedule of Node.js, generated by data/update/node-schedule.py '
         'from the source it names. Not edited by hand.')


def main():
    sha = common.ls_remote(REPO + '.git', 'main')[0][0]
    schedule = json.loads(common.fetch('%s/%s/schedule.json' % (RAW, sha)))
    lines = {}
    for key, line in schedule.items():
        m = re.fullmatch(r'v(\d+)', key)
        if m:
            lines[m.group(1)] = {f: line[f] for f in ('start', 'lts', 'end') if line.get(f)}
    if not lines or any('start' not in l or 'end' not in l for l in lines.values()):
        sys.exit('ERROR: schedule.json lists no line, or a line without start or end; has its layout changed?')
    values = {k: lines[k] for k in sorted(lines, key=int)}
    common.write('node-schedule', ABOUT, {'schedule': '%s/blob/%s/schedule.json' % (REPO, sha)}, values)


main()
