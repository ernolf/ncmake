# data/workflow-scripts.json: the package.json scripts the workflow templates of
# make workflows-install run.
#
#   scripts     per script a run: step of a template runs through npm run,
#               pnpm run, yarn run or npm test, with or without --if-present, the
#               templates that run it, by the name make workflows-install takes
#   templates   per template of scripts, its source as make workflows-list
#               names it
#
# A name both sources offer is the template of ncmake, as in make workflows-list.
#
# The templates are read at the head of the default branch of each source, which
# is what make workflows-install fetches.

import json
import re
import sys

import common

API = 'https://api.github.com/repos'
# In the lookup order of make workflows-list: the first source wins a name.
SOURCES = [
    ('ncmake', 'ernolf/ncmake-workflows', 'workflows'),
    ('nextcloud', 'nextcloud/.github', 'workflow-templates'),
]

ABOUT = ('The package.json scripts each workflow template of make workflows-install runs, '
         'generated by data/update/workflow-scripts.py from the sources it names. Not edited by hand.')

RUN_SCRIPT = re.compile(r'\b(?:npm|pnpm|yarn)\s+(?:run|run-script)\s+(?:--?[\w-]+(?:=\S+)?\s+)*([\w:.@/-]+)')
NPM_TEST = re.compile(r'\bnpm\s+(?:test|t)(?=\s|$)')


def run_blocks(text):
    """The commands of the run: keys of a workflow, inline or as a block scalar.
    The name of a step can mention a command too, so only run: counts."""
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        m = re.match(r'^(\s*)(?:-\s+)?run:\s*(.*?)\s*$', lines[i])
        i += 1
        if not m:
            continue
        indent, value = len(m.group(1)), m.group(2)
        if value[:1] not in ('|', '>'):
            out.append(value)
            continue
        body = []
        while i < len(lines) and (not lines[i].strip() or len(lines[i]) - len(lines[i].lstrip()) > indent):
            body.append(lines[i])
            i += 1
        out.append('\n'.join(body))
    return out


def scripts(text):
    found = set()
    for block in run_blocks(text):
        for line in block.splitlines():
            line = re.sub(r'(?:^|\s)#.*$', '', line)
            found.update(RUN_SCRIPT.findall(line))
            if NPM_TEST.search(line):
                found.add('test')
    return sorted(found)


def main():
    by_script = {}
    templates = {}
    seen = set()
    sources = {}
    for name, repo, folder in SOURCES:
        sha = common.ls_remote('https://github.com/%s.git' % repo, 'HEAD', kind='')[0][0]
        listing = json.loads(common.fetch('%s/%s/contents/%s?ref=%s' % (API, repo, folder, sha)))
        for entry in listing:
            if entry.get('type') != 'file' or not entry['name'].endswith(('.yml', '.yaml')):
                continue
            template = re.sub(r'\.ya?ml$', '', entry['name'])
            if template in seen:
                continue
            seen.add(template)
            run = scripts(common.fetch(entry['download_url']))
            for script in run:
                by_script.setdefault(script, []).append(template)
            if run:
                templates[template] = name
        sources[name] = 'https://github.com/%s/tree/%s/%s' % (repo, sha, folder)
    if not templates:
        sys.exit('ERROR: no template runs a script; has a layout changed?')

    values = {
        'scripts': {s: sorted(t) for s, t in sorted(by_script.items())},
        'templates': dict(sorted(templates.items())),
    }
    common.write('workflow-scripts', ABOUT, sources, values)


main()
