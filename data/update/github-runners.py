# data/github-runners.json: the runner labels of the Nextcloud workflows that
# GitHub does not host.
#
#   self_hosted  every label a runs-on: of the workflow templates of
#                nextcloud/.github or of the workflows of nextcloud/server names
#                that is none of GitHub's hosted labels, as the actionlint
#                lint-actions runs lists them (allGitHubHostedRunnerLabels of its
#                rule_runner_label.go), and none of the preset labels of a
#                self-hosted runner. Such a label exists only for the repositories
#                of the nextcloud organisation. A runs-on: that is an expression
#                names no label.

import json
import os
import re
import sys

import common

API = 'https://api.github.com/repos'
SOURCES = [
    ('nextcloud/.github', 'workflow-templates'),
    ('nextcloud/server', '.github/workflows'),
]
ACTIONLINT = 'https://github.com/rhysd/actionlint'
ACTIONLINT_RAW = 'https://raw.githubusercontent.com/rhysd/actionlint'
LINT_MK = os.path.join(os.path.dirname(common.DATA_DIR), 'mk', 'lint.mk')

ABOUT = ('The runner labels of the Nextcloud workflows that GitHub does not host, generated by '
         'data/update/github-runners.py from the sources it names. Not edited by hand.')


def go_list(text, name):
    m = re.search(r'^var %s = \[\]string\{(.*?)^\}' % name, text, re.M | re.S)
    if not m:
        sys.exit('ERROR: rule_runner_label.go has no %s' % name)
    return re.findall(r'"([^"]+)"', m.group(1))


def runs_on(text):
    """The labels the runs-on: keys of a workflow name, in scalar, flow or block
    form."""
    labels = []
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = re.match(r'^(\s*)runs-on:\s*(.*?)\s*(?:#.*)?$', line)
        if not m:
            continue
        value = m.group(2)
        if value.startswith('['):
            labels += [v.strip().strip('\'"') for v in value.strip('[]').split(',')]
        elif value:
            labels.append(value.strip('\'"'))
        else:
            for item in lines[i + 1:]:
                b = re.match(r'^\s*-\s*(.*?)\s*(?:#.*)?$', item)
                if not b:
                    break
                labels.append(b.group(1).strip('\'"'))
    return [l for l in labels if l and '${{' not in l]


def main():
    with open(LINT_MK, 'r', encoding='utf-8') as f:
        m = re.search(r'^actionlint_version\s*=\s*(\S+)', f.read(), re.M)
    if not m:
        sys.exit('ERROR: mk/lint.mk names no actionlint_version')
    tag = 'v' + m.group(1)
    go = common.fetch('%s/%s/rule_runner_label.go' % (ACTIONLINT_RAW, tag))
    known = set(go_list(go, 'allGitHubHostedRunnerLabels') + go_list(go, 'selfHostedRunnerPresetOSLabels')
                + go_list(go, 'selfHostedRunnerPresetOtherLabels'))

    found = set()
    sources = {'hosted': '%s/blob/%s/rule_runner_label.go' % (ACTIONLINT, tag), 'workflows': []}
    for repo, folder in SOURCES:
        sha = common.ls_remote('https://github.com/%s.git' % repo, 'HEAD', kind='')[0][0]
        listing = json.loads(common.fetch('%s/%s/contents/%s?ref=%s' % (API, repo, folder, sha)))
        for entry in listing:
            if entry.get('type') == 'file' and entry['name'].endswith(('.yml', '.yaml')):
                found.update(l.lower() for l in runs_on(common.fetch(entry['download_url'])))
        sources['workflows'].append('https://github.com/%s/tree/%s/%s' % (repo, sha, folder))
    if not found:
        sys.exit('ERROR: no runs-on: label was read; has a layout changed?')

    values = {'self_hosted': sorted(found - {k.lower() for k in known})}
    common.write('github-runners', ABOUT, sources, values)


main()
