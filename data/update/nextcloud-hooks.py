# data/nextcloud-hooks.json: the legacy hooks of the Nextcloud server that the
# developer manual names as removed, with the typed events that replace them.
#
#   hooks  per hook, <scope>::<signal> as the manual writes it without the
#          leading backslash (or the plain name where the manual gives no
#          scope):
#            removed     the major that removed it
#            deprecated  the major the manual says deprecated the hooks
#            events      the event classes the manual names as replacement
#
# The manual has one table "Hook | Replacement event" per release that removed
# hooks: in release_notes/critical_changes.rst for the major in development
# and in release_notes/previous/upgrade_to_<major>.rst once it is released.

import re
import sys

import common

REPO = 'https://github.com/nextcloud/documentation'
RAW = 'https://raw.githubusercontent.com/nextcloud/documentation'
NOTES = 'developer_manual/release_notes'

ABOUT = ('The legacy hooks of the Nextcloud server the developer manual names as removed, with the events that '
         'replace them, generated by data/update/nextcloud-hooks.py from the sources it names. Not edited by hand.')

TABLE = re.compile(r'^\.\. list-table::\n(?:[ \t]+:[^\n]*\n)*\s*\n((?:[ \t]+[^\n]*\n|\n)+)', re.M)
ROW = re.compile(r'^\s*\*\s+-\s+(.*)\n\s+-\s+(.*)$', re.M)
LITERAL = re.compile(r'``([^`]+)``')
REMOVED = re.compile(r'With Nextcloud (\d+) the following hooks were removed')
DEPRECATED = re.compile(r'deprecated in Nextcloud (\d+)')


def hook_tables(text, major):
    """[(removed, deprecated, rows)] of the hook tables of one release note."""
    out = []
    for m in TABLE.finditer(text):
        rows = ROW.findall(m.group(1))
        if not rows or [c.strip() for c in rows[0]] != ['Hook', 'Replacement event']:
            continue
        before = text[:m.start()]
        removed = REMOVED.findall(before)
        deprecated = DEPRECATED.findall(before)
        out.append((int(removed[-1]) if removed else major, int(deprecated[-1]) if deprecated else None, rows[1:]))
    return out


def main():
    heads = [ref for _, ref in common.ls_remote(REPO, 'refs/heads/stable*', 'refs/heads/master')]
    stable = sorted(int(m.group(1)) for m in (re.fullmatch(r'refs/heads/stable(\d+)', r) for r in heads) if m)
    if not stable or 'refs/heads/master' not in heads:
        sys.exit('ERROR: %s has no stable branch or no master' % REPO)
    commit = common.ls_remote(REPO, 'refs/heads/master')[0][0]
    # The notes of every released major are kept on master; the one in
    # development is critical_changes.rst.
    files = {major: '%s/previous/upgrade_to_%d.rst' % (NOTES, major) for major in range(stable[0], stable[-1] + 1)}
    files[stable[-1] + 1] = '%s/critical_changes.rst' % NOTES
    values = {'hooks': {}}
    sources = {}
    for major, file in sorted(files.items()):
        text = common.fetch('%s/%s/%s' % (RAW, commit, file), missing_ok=True)
        if text is None:
            continue
        for removed, deprecated, rows in hook_tables(text, major):
            sources[str(major)] = '%s/blob/%s/%s' % (REPO, commit, file)
            for hook, events in rows:
                names = LITERAL.findall(hook)
                if len(names) != 1:
                    sys.exit('ERROR: %s: the hook cell %r names no single hook' % (file, hook))
                values['hooks'][names[0].lstrip('\\')] = {
                    'removed': removed,
                    'deprecated': deprecated,
                    'events': [e.lstrip('\\') for e in LITERAL.findall(events)],
                }
    if not values['hooks']:
        sys.exit('ERROR: no hook table was read from %s; has the layout of the release notes changed?' % REPO)
    values['hooks'] = dict(sorted(values['hooks'].items()))
    common.write('nextcloud-hooks', ABOUT, sources, values)


main()
