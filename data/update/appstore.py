# data/appstore.json: what the App Store of Nextcloud accepts in a release, read
# from its source, nextcloud/appstore, never from the store itself.
#
#   licences       the SPDX ids the <licence> of info.xml may state: the licence
#                  type of nextcloudappstore/api/v1/release/info.xsd, up to its
#                  "Deprecated" comment
#   licences_from  the Nextcloud major that comment before them names: below a
#                  <nextcloud> min-version of that major, info.xml cannot state
#                  an SPDX id
#   deprecated     the values after the "Deprecated" comment, each with the name
#                  the store shows for it (nextcloudappstore/core/fixtures/
#                  licenses.json)
#   languages      the codes the store reads a CHANGELOG.<code>.md for: the
#                  LANGUAGES of the Django the store locks in poetry.lock, without
#                  the EXCLUDED_LANGS of nextcloudappstore/settings/base.py
#   excluded       those EXCLUDED_LANGS

import json
import re
import sys

import common

REPO = 'https://github.com/nextcloud/appstore'
RAW = 'https://raw.githubusercontent.com/nextcloud/appstore'
DJANGO = 'https://github.com/django/django'
DJANGO_RAW = 'https://raw.githubusercontent.com/django/django'

XSD = 'nextcloudappstore/api/v1/release/info.xsd'
FIXTURE = 'nextcloudappstore/core/fixtures/licenses.json'
SETTINGS = 'nextcloudappstore/settings/base.py'
LOCK = 'poetry.lock'
GLOBAL_SETTINGS = 'django/conf/global_settings.py'

ABOUT = ('What the Nextcloud App Store accepts in a release, the licences of info.xml and the '
         'languages of a changelog, generated by data/update/appstore.py from the sources it '
         'names. Not edited by hand.')


def licences(xsd):
    m = re.search(r'<xs:simpleType\s+name="licence">(.*?)</xs:simpleType>', xsd, re.S)
    if not m:
        sys.exit('ERROR: %s has no simpleType licence' % XSD)
    body = m.group(1)
    since = re.search(r'<!--[^>]*minVersion\s*>=\s*(\d+)[^>]*-->', body)
    parts = re.split(r'<!--\s*Deprecated\s*-->', body)
    if not since or len(parts) != 2:
        sys.exit('ERROR: the licence type of %s has no minVersion or no Deprecated comment; has its layout changed?' % XSD)
    values = lambda text: re.findall(r'<xs:enumeration\s+value="([^"]+)"', text)
    return values(parts[0]), int(since.group(1)), values(parts[1])


def django_version(lock):
    m = re.search(r'^name = "django"\nversion = "([^"]+)"', lock, re.M)
    if not m:
        sys.exit('ERROR: %s locks no django' % LOCK)
    return m.group(1)


def django_languages(text):
    m = re.search(r'^LANGUAGES = \[(.*?)^\]', text, re.M | re.S)
    if not m:
        sys.exit('ERROR: %s has no LANGUAGES' % GLOBAL_SETTINGS)
    return re.findall(r'^\s*\("([^"]+)",\s*gettext_noop\(', m.group(1), re.M)


def main():
    sha = common.ls_remote(REPO + '.git', 'master')[0][0]
    raw = lambda path: common.fetch('%s/%s/%s' % (RAW, sha, path))
    blob = lambda path: '%s/blob/%s/%s' % (REPO, sha, path)

    accepted, since, deprecated = licences(raw(XSD))
    names = {x['pk']: x['fields'].get('name') for x in json.loads(raw(FIXTURE))}
    missing = [d for d in deprecated if not names.get(d)]
    if missing:
        sys.exit('ERROR: %s names no licence %s' % (FIXTURE, ', '.join(missing)))

    m = re.search(r'^EXCLUDED_LANGS\s*=\s*\(([^)]*)\)', raw(SETTINGS), re.M)
    if not m:
        sys.exit('ERROR: %s has no EXCLUDED_LANGS' % SETTINGS)
    excluded = re.findall(r'"([^"]+)"', m.group(1))
    version = django_version(raw(LOCK))
    languages = django_languages(common.fetch('%s/%s/%s' % (DJANGO_RAW, version, GLOBAL_SETTINGS)))
    if not accepted or not languages:
        sys.exit('ERROR: no licence or no language was read; has a layout changed?')

    values = {
        'licences': accepted,
        'licences_from': since,
        'deprecated': {d: names[d] for d in deprecated},
        'languages': sorted(c for c in languages if c not in excluded),
        'excluded': excluded,
    }
    sources = {
        'licences': blob(XSD),
        'deprecated': blob(FIXTURE),
        'languages': '%s/blob/%s/%s' % (DJANGO, version, GLOBAL_SETTINGS),
        'django': blob(LOCK),
        'excluded': blob(SETTINGS),
    }
    common.write('appstore', ABOUT, sources, values)


main()
