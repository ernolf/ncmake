# data/gitleaks-rules.json: the rules of the gitleaks release secrets-audit runs.
#
#   rules  the id of every [[rules]] table of config/gitleaks.toml at the release
#          data/tools.json names, in the order of the file
#
# secrets-audit treats some of them apart; its self-test holds the ids it names
# against this list, so a rule gitleaks renames or drops is noticed.

import json
import os
import re
import sys

import common

REPO = 'https://github.com/gitleaks/gitleaks'
RAW = 'https://raw.githubusercontent.com/gitleaks/gitleaks'
CONFIG = 'config/gitleaks.toml'
TOOLS = os.path.join(common.DATA_DIR, 'tools.json')

ABOUT = ('The rule ids of the gitleaks release secrets-audit runs, generated by '
         'data/update/gitleaks-rules.py from the sources it names. Not edited by hand.')


def main():
    with open(TOOLS, 'r', encoding='utf-8') as f:
        version = json.load(f)['values'].get('gitleaks', {}).get('version')
    if not version:
        sys.exit('ERROR: data/tools.json names no gitleaks version')
    tag = 'v' + version
    text = common.fetch('%s/%s/%s' % (RAW, tag, CONFIG))
    rules = re.findall(r'^\[\[rules\]\]\s*\nid\s*=\s*"([^"]+)"', text, re.M)
    if not rules or len(rules) != len(re.findall(r'^\[\[rules\]\]', text, re.M)):
        sys.exit('ERROR: not every rule of %s at %s has its id on its first line; has its layout changed?' % (CONFIG, tag))
    common.write('gitleaks-rules', ABOUT, {'rules': '%s/blob/%s/%s' % (REPO, tag, CONFIG)}, {'rules': rules})


main()
