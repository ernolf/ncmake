# data/nextcloud-ocp.json: the public PHP API of the Nextcloud server over its
# majors, read from the package nextcloud/ocp, which the server publishes per
# stable branch in the repository nextcloud-deps/ocp, and from master.
#
#   majors   the majors read: one per branch stable<major>, and the one after
#            the highest for master
#   classes  per class, interface, trait and enum below OCP\ and NCU\:
#              kind        class, interface, trait or enum
#              majors      the first and the last major that has it
#              parents     what it extends and implements, in the last major
#                          that has it
#              consumable  the first major in which it carries the attribute
#                          Consumable: the server may add methods to it, so an
#                          app calls it and does not implement it
#              methods     per method that is not private, the first and the
#                          last major that has it; a protected one is what a
#                          class of an app that extends or uses it calls. A
#                          method that carries #[\Override] counts from the
#                          first major on in which a parent declares it; a
#                          parent outside OCP\ and NCU\, such as a PSR
#                          interface, is not read and counts as declaring it
#              constants   per constant that is not private, and per case of an
#                          enum, the first and the last major that has it
#              deprecated  the first major whose doc comment of the class
#                          carries @deprecated, and the text of the tag in the
#                          last major that carries it, without the version
#                          it names
#              deprecated_members
#                          the same per method and per constant
#
# The files are read with expressions, not with a PHP parser: the package holds
# one declaration per file, formatted by the coding standard of the server. A
# file with a class this cannot read stops the script.

import io
import re
import sys
import tarfile

import common

REPO = 'https://github.com/nextcloud-deps/ocp'
ARCHIVE = 'https://codeload.github.com/nextcloud-deps/ocp/tar.gz/%s'
ROOTS = ('OCP/', 'NCU/')

ABOUT = ('The classes, methods and constants of the public PHP API of the Nextcloud server, with the majors that '
         'have each and those that deprecate it, generated by data/update/nextcloud-ocp.py from the sources it names. Not edited by hand.')

NAME = r'[A-Za-z_][A-Za-z0-9_]*'
QNAME = r'\\?%s(?:\\%s)*' % (NAME, NAME)
# A comment or a string, whichever starts first: an apostrophe in a comment opens
# no string, and a // in a string no comment.
SKIP = re.compile(r'''(/\*.*?\*/|//[^\n]*|(?m:^\s*#(?!\[)[^\n]*))|'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"''', re.S)
NAMESPACE = re.compile(r'^\s*namespace\s+(%s)\s*;' % QNAME, re.M)
USE = re.compile(r'^use\s+(%s)(?:\s+as\s+(%s))?\s*;' % (QNAME, NAME), re.M)
DECL = re.compile(
    r'^((?:#\[[^\n]*\]\s*)*)(?:(?:abstract|final|readonly)\s+)*(class|interface|trait|enum)\s+(%s)'
    r'(?:\s*:\s*%s)?(?:\s+extends\s+([^{]*?))?(?:\s+implements\s+([^{]*?))?\s*\{' % (NAME, NAME), re.M)
METHOD = re.compile(r'^\s*((?:(?:abstract|final|public|protected|private|static)\s+)*)function\s+&?\s*(%s)\s*\(' % NAME, re.M)
# A method that carries the attribute Override, past further attributes and
# modifiers.
OVERRIDE = re.compile(r'#\[\s*\\?Override\s*\]\s*(?:#\[[^\n]*\]\s*)*(?:(?:abstract|final|public|protected|static)\s+)*'
                      r'function\s+&?\s*(%s)\s*\(' % NAME)
CONST = re.compile(r'^\s*((?:(?:final|public|protected|private)\s+)*)const\s+(?:%s\s+)?(%s)\s*=' % (QNAME, NAME), re.M)
CASE = re.compile(r'^\s*case\s+(%s)\s*[=;]' % NAME, re.M)
ATTRIBUTE = re.compile(r'#\[\s*(%s)' % QNAME)
# A doc comment and the declaration it documents, read from the text before
# comments are removed: a class, a method or a constant, past attributes and
# modifiers.
DOC = re.compile(
    r'/\*\*((?:(?!\*/).)*)\*/\s*(?:#\[[^\n]*\]\s*)*'
    r'(?:(?:abstract|final|public|protected|private|static|readonly)\s+)*'
    r'(?:(?:class|interface|trait|enum)\s+(%s)|function\s+&?\s*(%s)\s*\(|const\s+(?:%s\s+)?(%s)\s*=|case\s+(%s)\b)'
    % (NAME, NAME, QNAME, NAME, NAME), re.S)
DEPRECATED = re.compile(r'@deprecated\b((?:(?!\n\s*\*?\s*@).)*)', re.S)


def deprecations(text):
    """(text or None for the class, {member: text}) of what the doc comments of
    one file mark @deprecated; the text is what follows the tag, without the
    asterisks of the comment."""
    whole, members = None, {}
    for m in DOC.finditer(text):
        tag = DEPRECATED.search(m.group(1))
        if not tag:
            continue
        note = ' '.join(re.sub(r'^\s*\*\s?', '', line).strip() for line in tag.group(1).split('\n')).strip()
        # The version the tag names is left out: the first major whose package
        # carries the tag is recorded beside the text.
        note = re.sub(r'^v?\d+(?:\.\d+)*\s*[-:,]?\s*', '', note)
        note = re.sub(r'\{@(?:see|link)\s+([^}]*)\}', r'\1', note)
        if m.group(2):
            whole = note
        else:
            members[m.group(3) or m.group(4) or m.group(5)] = note
    return whole, members


def resolve(name, namespace, uses):
    """The fully qualified form of a class name as PHP resolves it."""
    if name.startswith('\\'):
        return name[1:]
    first, _, rest = name.partition('\\')
    if first in uses:
        return uses[first] + ('\\' + rest if rest else '')
    return (namespace + '\\' if namespace else '') + name


def declarations(text):
    """[(name, kind, parents, attributes, methods, constants, overrides)] of one file."""
    text = SKIP.sub(lambda m: '' if m.group(1) else "''", text)
    m = NAMESPACE.search(text)
    namespace = m.group(1) if m else ''
    uses = {}
    for full, alias in USE.findall(text):
        full = full.lstrip('\\')
        uses[alias or full.rsplit('\\', 1)[-1]] = full
    found = []
    decls = list(DECL.finditer(text))
    for i, d in enumerate(decls):
        attributes, kind, name, extends, implements = d.groups()
        parents = [resolve(p.strip(), namespace, uses)
                   for part in (extends, implements) if part for p in part.split(',') if p.strip()]
        body = text[d.end():decls[i + 1].start() if i + 1 < len(decls) else len(text)]
        methods = sorted({n for modifiers, n in METHOD.findall(body)
                          if 'private' not in modifiers.split()})
        constants = sorted({n for modifiers, n in CONST.findall(body) if 'private' not in modifiers.split()}
                           | (set(CASE.findall(body)) if kind == 'enum' else set()))
        marks = [resolve(a, namespace, uses) for a in ATTRIBUTE.findall(attributes)]
        overrides = sorted(set(OVERRIDE.findall(body)) & set(methods))
        found.append((resolve(name, namespace, uses), kind, sorted(set(parents)), marks, methods, constants, overrides))
    return found


def read(ref):
    """{class: (kind, parents, attributes, methods, constants, overrides,
    deprecations)} of the package at ref."""
    data = common.fetch(ARCHIVE % ref, binary=True)
    classes = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as tar:
        for member in tar:
            path = member.name.split('/', 1)[-1]
            if not member.isfile() or not path.endswith('.php') or not path.startswith(ROOTS):
                continue
            text = tar.extractfile(member).read().decode('utf-8', 'replace')
            found = declarations(text)
            if not found and re.search(r'^(?:abstract |final )*(?:class|interface|trait|enum) ', text, re.M):
                sys.exit('ERROR: %s of %s declares a class this script cannot read' % (path, ref))
            # A doc comment cannot be told apart between two declarations of one
            # file, so a deprecation there stops the script rather than land on
            # the wrong class.
            notes = deprecations(text)
            if len(found) > 1 and (notes[0] is not None or notes[1]):
                sys.exit('ERROR: %s of %s declares more than one class and deprecates something' % (path, ref))
            for name, kind, parents, marks, methods, constants, overrides in found:
                classes[name] = (kind, parents, marks, methods, constants, overrides, notes)
    if not classes:
        sys.exit('ERROR: %s has no class below %s' % (ref, ' or '.join(ROOTS)))
    return classes


def inherit(values, parents_of, overriding):
    """Move the first major of each method that carries #[Override] back to the
    first major from which on a parent declares it without a gap: the server
    declared again what the class had before, and a call of it works there."""
    classes, majors = values['classes'], values['majors']

    def outside(name):
        return not name.startswith(('OCP\\', 'NCU\\'))

    def declares(name, method, major, foreign):
        """Whether name or a parent of it declares method in major; of the
        parents outside the API only those in foreign count."""
        if outside(name):
            return name in foreign
        c = classes.get(name)
        span = c['methods'].get(method) if c else None
        if span and span[0] <= major <= span[1]:
            return True
        return any(declares(p, method, major, foreign) for p in parents_of.get(name, {}).get(major, ()))

    def reached(name, major):
        """The parents outside the API that name reaches in major."""
        found = set()
        for p in parents_of.get(name, {}).get(major, ()):
            found |= {p} if outside(p) else reached(p, major)
        return found

    # The first major each method has in the packages, before any moves.
    first = {(name, method): classes[name]['methods'][method][0]
             for name, methods in overriding.items() for method in methods}
    # A parent that overrides as well may move first, so repeat until nothing moves.
    moved = True
    while moved:
        moved = False
        for name, methods in overriding.items():
            c = classes[name]
            for method in sorted(methods):
                span = c['methods'][method]
                # Where a parent of the API declares it in the first major, the
                # method overrides that one; otherwise one of the parents outside
                # the API it reaches there, whose methods are not read.
                at = first[name, method]
                foreign = set() if any(declares(p, method, at, set()) for p in parents_of[name].get(at, ())) else reached(name, at)
                earlier = [major for major in majors if major < span[0]]
                for major in reversed(earlier):
                    if not any(declares(p, method, major, foreign) for p in parents_of[name].get(major, ())):
                        break
                    span[0] = major
                    moved = True


def main():
    heads = {ref: sha for sha, ref in common.ls_remote(REPO, 'refs/heads/stable*', 'refs/heads/master')}
    stable = sorted(int(m.group(1)) for m in (re.fullmatch(r'refs/heads/stable(\d+)', r) for r in heads) if m)
    if not stable or 'refs/heads/master' not in heads:
        sys.exit('ERROR: %s has no stable branch or no master' % REPO)
    refs = {major: 'refs/heads/stable%d' % major for major in stable}
    refs[stable[-1] + 1] = 'refs/heads/master'

    values = {'majors': sorted(refs), 'classes': {}}
    sources = {}
    # Per class the parents of each major, and the methods that carry
    # #[\Override] in any of them.
    parents_of, overriding = {}, {}
    for major in sorted(refs):
        sha = heads[refs[major]]
        sources[str(major)] = '%s/tree/%s' % (REPO, sha)
        for name, (kind, parents, marks, methods, constants, overrides, (whole, members)) in read(sha).items():
            parents_of.setdefault(name, {})[major] = parents
            overriding.setdefault(name, set()).update(overrides)
            c = values['classes'].setdefault(name, {'kind': kind, 'majors': [major, major], 'parents': parents,
                                                    'methods': {}, 'constants': {}, 'deprecated_members': {}})
            c['kind'], c['parents'] = kind, parents
            c['majors'][1] = major
            if 'consumable' not in c and any(a.rsplit('\\', 1)[-1] == 'Consumable' for a in marks):
                c['consumable'] = major
            for method in methods:
                c['methods'].setdefault(method, [major, major])[1] = major
            for constant in constants:
                c['constants'].setdefault(constant, [major, major])[1] = major
            # The first major that carries the tag, and the text of the last one.
            if whole is not None:
                c['deprecated'] = [c.get('deprecated', [major])[0], whole]
            for member, note in members.items():
                if member in c['methods'] or member in c['constants']:
                    c['deprecated_members'][member] = [c['deprecated_members'].get(member, [major])[0], note]
    inherit(values, parents_of, overriding)
    for c in values['classes'].values():
        c['constants'] = dict(sorted(c['constants'].items()))
        c['deprecated_members'] = dict(sorted(c['deprecated_members'].items()))
    values['classes'] = {name: values['classes'][name] for name in sorted(values['classes'])}
    common.write('nextcloud-ocp', ABOUT, sources, values)


main()
