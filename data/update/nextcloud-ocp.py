# data/nextcloud-ocp.json: the public PHP API of the Nextcloud server over its
# majors, read from the package nextcloud/ocp, which the server publishes per
# stable branch in the repository nextcloud-deps/ocp, and from master.
#
#   majors   the majors read: one per branch stable<major>, and the one after
#            the highest for master
#   classes  per class, interface, trait and enum below OCP\ and NCU\:
#              kind        class, interface, trait or enum
#              majors      the first and the last major that has it
#              parents     what it extends and implements, in the last major
#                          that has it
#              consumable  the first major in which it carries the attribute
#                          Consumable: the server may add methods to it, so an
#                          app calls it and does not implement it
#              methods     per method that is not private, the first and the
#                          last major that has it; a protected one is what a
#                          class of an app that extends or uses it calls
#
# The files are read with expressions, not with a PHP parser: the package holds
# one declaration per file, formatted by the coding standard of the server. A
# file with a class this cannot read stops the script.

import io
import re
import sys
import tarfile

import common

REPO = 'https://github.com/nextcloud-deps/ocp'
ARCHIVE = 'https://codeload.github.com/nextcloud-deps/ocp/tar.gz/%s'
ROOTS = ('OCP/', 'NCU/')

ABOUT = ('The classes and methods of the public PHP API of the Nextcloud server, with the majors that '
         'have each, generated by data/update/nextcloud-ocp.py from the sources it names. Not edited by hand.')

NAME = r'[A-Za-z_][A-Za-z0-9_]*'
QNAME = r'\\?%s(?:\\%s)*' % (NAME, NAME)
# A comment or a string, whichever starts first: an apostrophe in a comment opens
# no string, and a // in a string no comment.
SKIP = re.compile(r'''(/\*.*?\*/|//[^\n]*|(?m:^\s*#(?!\[)[^\n]*))|'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"''', re.S)
NAMESPACE = re.compile(r'^\s*namespace\s+(%s)\s*;' % QNAME, re.M)
USE = re.compile(r'^use\s+(%s)(?:\s+as\s+(%s))?\s*;' % (QNAME, NAME), re.M)
DECL = re.compile(
    r'^((?:#\[[^\n]*\]\s*)*)(?:(?:abstract|final|readonly)\s+)*(class|interface|trait|enum)\s+(%s)'
    r'(?:\s*:\s*%s)?(?:\s+extends\s+([^{]*?))?(?:\s+implements\s+([^{]*?))?\s*\{' % (NAME, NAME), re.M)
METHOD = re.compile(r'^\s*((?:(?:abstract|final|public|protected|private|static)\s+)*)function\s+&?\s*(%s)\s*\(' % NAME, re.M)
ATTRIBUTE = re.compile(r'#\[\s*(%s)' % QNAME)


def resolve(name, namespace, uses):
    """The fully qualified form of a class name as PHP resolves it."""
    if name.startswith('\\'):
        return name[1:]
    first, _, rest = name.partition('\\')
    if first in uses:
        return uses[first] + ('\\' + rest if rest else '')
    return (namespace + '\\' if namespace else '') + name


def declarations(text):
    """[(name, kind, parents, attributes, methods)] of one file."""
    text = SKIP.sub(lambda m: '' if m.group(1) else "''", text)
    m = NAMESPACE.search(text)
    namespace = m.group(1) if m else ''
    uses = {}
    for full, alias in USE.findall(text):
        full = full.lstrip('\\')
        uses[alias or full.rsplit('\\', 1)[-1]] = full
    found = []
    decls = list(DECL.finditer(text))
    for i, d in enumerate(decls):
        attributes, kind, name, extends, implements = d.groups()
        parents = [resolve(p.strip(), namespace, uses)
                   for part in (extends, implements) if part for p in part.split(',') if p.strip()]
        body = text[d.end():decls[i + 1].start() if i + 1 < len(decls) else len(text)]
        methods = sorted({n for modifiers, n in METHOD.findall(body)
                          if 'private' not in modifiers.split()})
        marks = [resolve(a, namespace, uses) for a in ATTRIBUTE.findall(attributes)]
        found.append((resolve(name, namespace, uses), kind, sorted(set(parents)), marks, methods))
    return found


def read(ref):
    """{class: (kind, parents, attributes, methods)} of the package at ref."""
    data = common.fetch(ARCHIVE % ref, binary=True)
    classes = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as tar:
        for member in tar:
            path = member.name.split('/', 1)[-1]
            if not member.isfile() or not path.endswith('.php') or not path.startswith(ROOTS):
                continue
            text = tar.extractfile(member).read().decode('utf-8', 'replace')
            found = declarations(text)
            if not found and re.search(r'^(?:abstract |final )*(?:class|interface|trait|enum) ', text, re.M):
                sys.exit('ERROR: %s of %s declares a class this script cannot read' % (path, ref))
            for name, kind, parents, marks, methods in found:
                classes[name] = (kind, parents, marks, methods)
    if not classes:
        sys.exit('ERROR: %s has no class below %s' % (ref, ' or '.join(ROOTS)))
    return classes


def main():
    heads = {ref: sha for sha, ref in common.ls_remote(REPO, 'refs/heads/stable*', 'refs/heads/master')}
    stable = sorted(int(m.group(1)) for m in (re.fullmatch(r'refs/heads/stable(\d+)', r) for r in heads) if m)
    if not stable or 'refs/heads/master' not in heads:
        sys.exit('ERROR: %s has no stable branch or no master' % REPO)
    refs = {major: 'refs/heads/stable%d' % major for major in stable}
    refs[stable[-1] + 1] = 'refs/heads/master'

    values = {'majors': sorted(refs), 'classes': {}}
    sources = {}
    for major in sorted(refs):
        sha = heads[refs[major]]
        sources[str(major)] = '%s/tree/%s' % (REPO, sha)
        for name, (kind, parents, marks, methods) in read(sha).items():
            c = values['classes'].setdefault(name, {'kind': kind, 'majors': [major, major], 'parents': parents, 'methods': {}})
            c['kind'], c['parents'] = kind, parents
            c['majors'][1] = major
            if 'consumable' not in c and any(a.rsplit('\\', 1)[-1] == 'Consumable' for a in marks):
                c['consumable'] = major
            for method in methods:
                c['methods'].setdefault(method, [major, major])[1] = major
    values['classes'] = {name: values['classes'][name] for name in sorted(values['classes'])}
    common.write('nextcloud-ocp', ABOUT, sources, values)


main()
