# data/nextcloud-server.json: the majors of nextcloud/server, the PHP each one
# runs on, the apps whose routes may leave /apps/<id> and what it checks before
# it applies a migration.
#
#   master      the major in development, $OC_Version of version.php on master
#   newest      the highest major among the release tags vX.Y.Z; a tag with a
#               beta or rc suffix is no release
#   maintained  the majors under "Currently supported versions" of the server's
#               Maintenance and Release Schedule
#   eol         the newest major under "EOL Versions" of that page
#   php         per major, the PHP minors lib/versioncheck.php of its stable
#               branch, or of master for the major in development, lets the
#               server run on: it refuses PHP_VERSION_ID < floor and >= the minor
#               after the ceiling. A branch whose versioncheck.php states neither
#               is left out.
#   extensions  per major, the PHP extensions the require of composer.json of
#               that branch states as ext-*: what a server of that major cannot
#               run without. A branch whose composer.json states none is left
#               out.
#   root_urls   per major, the apps of rootUrlApps in the route parser of that
#               branch: the only ones whose routes outside OCS may state a root
#               other than /apps/<id>. A branch whose route parser has no such
#               list is left out.
#   migrations  what lib/private/DB/MigrationService.php checks in the target
#               schema of a migration before it applies it:
#     rules         per major, read from its branch:
#       oracle_only   whether the names are checked only where the app does not
#                     rule out the database named in oracle: up to 32 the name
#                     checks are part of the Oracle checks
#       oracle        the database whose checks an app that lists databases in
#                     <dependencies> gets only where it lists this one
#       name          the longest column, index, foreign key and sequence name,
#                     and the longest primary key name the app sets itself
#       table         the longest table name as the app writes it, without the
#                     prefix: that name plus prefixes times the prefix may be at
#                     most max
#       primary       the same for the table name of a table whose primary key
#                     keeps the name the database gives it
#       bool_notnull  whether a new boolean column must not be NotNull
#       string_length the longest new string column, null where none is checked
#       unique_names  whether an index or foreign key name that is not unique
#                     across the schema stops an install
#                   Every branch read stops a column it adds to an existing
#                   table that is NotNull with '' as its default; the run fails
#                   where that check is not found.
#     table_prefix  the table prefix of a server whose config does not set one,
#                   'dbtableprefix' of config/config.sample.php on master
#     types         the column types by the class constants an app names them
#                   with: lib/public/DB/Types.php on master and Types.php of
#                   doctrine/dbal as composer.lock of nextcloud/3rdparty on
#                   master pins it
#     column_notnull whether a column without the option notnull is NotNull,
#                    Column.php of that doctrine/dbal

import json
import re
import sys

import common

REPO = 'https://github.com/nextcloud/server'
RAW = 'https://raw.githubusercontent.com/nextcloud/server'
WIKI = 'https://github.com/nextcloud/server.wiki.git'
SCHEDULE = 'https://raw.githubusercontent.com/wiki/nextcloud/server/Maintenance-and-Release-Schedule.md'

# The route parser moved once; the first file of a branch that has the list is read.
ROUTING = ('lib/private/AppFramework/Routing/RouteParser.php', 'lib/private/AppFramework/Routing/RouteConfig.php')
MIGRATION = 'lib/private/DB/MigrationService.php'
THIRDPARTY = 'https://raw.githubusercontent.com/nextcloud/3rdparty/master/composer.lock'
DBAL = 'https://raw.githubusercontent.com/doctrine/dbal/%s/%s'
# doctrine/dbal moved its sources from lib/Doctrine/DBAL/ to src/ in 3.0.
DBAL_DIRS = ('src', 'lib/Doctrine/DBAL')
LIMIT = r'(\d+|\$MAX_NAME_LENGTH)'

ABOUT = ('The majors of nextcloud/server, the PHP each one runs on, the PHP extensions it '
         'requires, the apps whose routes may state a root and what it checks in the schema '
         'of a migration, generated by '
         'data/update/nextcloud-server.py from the sources it names. Not edited by hand.')


def minor(version_id):
    return '%d.%d' % (version_id // 10000, version_id % 10000 // 100)


def php_range(text):
    floor = re.search(r'PHP_VERSION_ID\s*<\s*(\d+)', text)
    above = re.search(r'PHP_VERSION_ID\s*>=\s*(\d+)', text)
    r = {}
    if floor:
        r['min'] = minor(int(floor.group(1)))
    if above:
        r['max'] = minor(int(above.group(1)) - 100)
    return r


def extensions(text):
    require = json.loads(text).get('require') or {}
    return sorted(k[len('ext-'):].lower() for k in require if k.lower().startswith('ext-'))


def root_url_apps(text):
    m = re.search(r'\brootUrlApps\s*=\s*\[(.*?)\]', text, re.S)
    return sorted(re.findall(r"""['"]([^'"]+)['"]""", m.group(1))) if m else []


def migration_rules(text, where):
    """The checks of MigrationService.php, None for a branch without them. A
    check whose code has a shape not known here stops the run, so a change of
    the server shows up as a failed update instead of a wrong rule."""
    # Up to 21 the function was ensureOracleIdentifierLengthLimit.
    if not re.search(r'function ensureOracle\w+\(Schema', text):
        return None
    named = re.search(r'\$MAX_NAME_LENGTH\s*=\s*(\d+)', text)

    def limit(s):
        if s.isdigit():
            return int(s)
        if not named:
            sys.exit('ERROR: %s uses $MAX_NAME_LENGTH without setting it' % where)
        return int(named.group(1))

    def stop(what):
        sys.exit('ERROR: %s: the check of %s has changed; teach data/update/nextcloud-server.py its new shape' % (where, what))

    names = {limit(s) for s in re.findall(r'strlen\(\$(?:thing|sequence)->getName\(\)\)\s*>\s*' + LIMIT, text)}
    names |= {limit(s) for s in re.findall(r'!\$isUsingDefaultName\s*&&\s*\\?strlen\(\$indexName\)\s*>\s*' + LIMIT, text)}
    if len(names) != 1:
        stop('the name lengths')

    # The schema holds the table names with the prefix. Up to 32 the check takes
    # the prefix off again; from 33 it adds it a second time.
    table = re.search(r'strlen\(\$table->getName\(\)\)\s*([-+])\s*\$prefixLength\s*>\s*' + LIMIT, text)
    if not table:
        stop('the table name length')
    table = {'max': limit(table.group(2)), 'prefixes': 0 if table.group(1) == '-' else 2}

    old = re.search(r'\$isUsingDefaultName\s*&&\s*\\?strlen\(\$table->getName\(\)\)\s*-\s*\$prefixLength\s*>=\s*(\d+)', text)
    new = re.search(r'\$isUsingDefaultName\s*&&\s*\\?strlen\(\$defaultName\)\s*\+\s*\$prefixLength\s*>\s*' + LIMIT, text)
    suffix = re.search(r"\$defaultName\s*=\s*strtolower\(\$table->getName\(\)\s*\.\s*'([^']+)'\)", text)
    if old:
        primary = {'max': int(old.group(1)) - 1, 'prefixes': 0}
    elif new and suffix:
        primary = {'max': limit(new.group(1)) - len(suffix.group(1)), 'prefixes': 2}
    else:
        stop('the default primary key name')

    oracle = re.search(r"\$database\s*===\s*'(\w+)'", text)
    empty = re.search(r"getNotnull\(\)\s*&&\s*\$\w+->getDefault\(\)\s*===\s*''\s*&&\s*\$sourceTable\s+instanceof\s+Table"
                      r"\s*&&\s*!\$sourceTable->hasColumn\([^)]*\)\)\s*\)\s*\{\s*(?://[^\n]*\s*)*throw", text)
    if not oracle or not empty:
        stop('the Oracle database' if not oracle else 'the empty default')
    string = re.search(r'getLength\(\)\s*>\s*(\d+)\s*&&[^{]*Types::STRING\)\s*\{\s*throw', text)
    return {
        'oracle_only': '$this->ensureNamingConstraints(' not in text,
        'oracle': oracle.group(1),
        'name': names.pop(),
        'table': table,
        'primary': primary,
        'bool_notnull': bool(re.search(r'getNotnull\(\)\s*&&\s*\$\w+->getType\(\)->getName\(\)\s*===\s*Types::BOOLEAN\)\s*\{\s*throw', text)),
        'string_length': int(string.group(1)) if string else None,
        'unique_names': '$this->ensureUniqueNamesConstraints($targetSchema, true)' in text,
    }


def constants(text):
    """{NAME: value} of the string constants of a class."""
    return dict(re.findall(r"const\s+([A-Z_][A-Z0-9_]*)\s*=\s*'([^']*)'", text))


def dbal_file(version, name):
    """A file of doctrine/dbal at a release, and the URL it was read from."""
    for d in DBAL_DIRS:
        url = DBAL % (version, '%s/%s' % (d, name))
        text = common.fetch(url, missing_ok=True)
        if text is not None:
            return text, url.replace('https://raw.githubusercontent.com/doctrine/dbal/', 'https://github.com/doctrine/dbal/blob/')
    sys.exit('ERROR: doctrine/dbal %s has no %s' % (version, name))


def migration_defaults(master_sha):
    """What a migration gets without stating it: the table prefix, the values of
    the type constants and whether a column is NotNull."""
    sample = common.fetch('%s/%s/config/config.sample.php' % (RAW, master_sha))
    prefix = re.search(r"'dbtableprefix'\s*=>\s*'([^']*)'", sample)
    ocp = constants(common.fetch('%s/%s/lib/public/DB/Types.php' % (RAW, master_sha)))
    lock = json.loads(common.fetch(THIRDPARTY))
    dbal = next((p['version'] for p in lock.get('packages') or [] if p['name'] == 'doctrine/dbal'), None)
    if not prefix or not ocp or not dbal:
        sys.exit('ERROR: no dbtableprefix in config.sample.php, no constant in Types.php or no doctrine/dbal in %s' % THIRDPARTY)
    types_text, types_url = dbal_file(dbal, 'Types/Types.php')
    column_text, column_url = dbal_file(dbal, 'Schema/Column.php')
    notnull = re.search(r'\$_notnull\s*=\s*(true|false)\s*;', column_text)
    if not notnull:
        sys.exit('ERROR: Column.php of doctrine/dbal %s sets no default for $_notnull' % dbal)
    types = {'OCP\\DB\\Types::' + k: v for k, v in ocp.items()}
    types.update({'Doctrine\\DBAL\\Types\\Types::' + k: v for k, v in constants(types_text).items()})
    values = {'table_prefix': prefix.group(1), 'types': dict(sorted(types.items())), 'column_notnull': notnull.group(1) == 'true'}
    sources = {
        'table_prefix': '%s/blob/%s/config/config.sample.php' % (REPO, master_sha),
        'types': ['%s/blob/%s/lib/public/DB/Types.php' % (REPO, master_sha), types_url],
        'column_notnull': column_url,
    }
    return values, sources


def schedule_majors(text, heading):
    """The majors in the bold first column of the table below heading."""
    majors = []
    inside = False
    for line in text.splitlines():
        if line.startswith('## '):
            inside = line.strip() == heading
            continue
        m = inside and re.match(r'^\|\s*\*\*(\d+)\*\*', line)
        if m:
            majors.append(int(m.group(1)))
    return majors


def main():
    heads = {ref[len('refs/heads/'):]: sha for sha, ref in common.ls_remote(REPO + '.git', 'master', 'stable*')}
    master_sha = heads.get('master')
    if not master_sha:
        sys.exit('ERROR: %s has no branch master' % REPO)
    version = common.fetch('%s/%s/version.php' % (RAW, master_sha))
    m = re.search(r'^\$OC_Version\s*=\s*\[\s*(\d+)', version, re.M)
    if not m:
        sys.exit('ERROR: no $OC_Version in version.php of master')
    master = int(m.group(1))

    php = {}
    branches = {}
    ext = {}
    ext_from = {}
    roots = {}
    roots_from = {}
    rules = {}
    rules_from = {}
    stable = sorted((int(b[len('stable'):]), b) for b in heads if re.fullmatch(r'stable\d+', b))
    for major, branch in stable + [(master, 'master')]:
        text = common.fetch('%s/%s/lib/versioncheck.php' % (RAW, heads[branch]), missing_ok=True)
        r = php_range(text or '')
        if r:
            php[str(major)] = r
            branches[str(major)] = {'branch': branch, 'commit': heads[branch]}
        exts = extensions(common.fetch('%s/%s/composer.json' % (RAW, heads[branch]), missing_ok=True) or '{}')
        if exts:
            ext[str(major)] = exts
            ext_from[str(major)] = '%s/blob/%s/composer.json' % (REPO, heads[branch])
        for file in ROUTING:
            apps = root_url_apps(common.fetch('%s/%s/%s' % (RAW, heads[branch], file), missing_ok=True) or '')
            if apps:
                roots[str(major)] = apps
                roots_from[str(major)] = '%s/blob/%s/%s' % (REPO, heads[branch], file)
                break
        # Only the majors with a PHP range: older branches check in shapes of
        # their own, and no major the analysers know is among them.
        if str(major) not in php:
            continue
        r = migration_rules(common.fetch('%s/%s/%s' % (RAW, heads[branch], MIGRATION), missing_ok=True) or '', '%s of %s' % (MIGRATION, branch))
        if r:
            rules[str(major)] = r
            rules_from[str(major)] = '%s/blob/%s/%s' % (REPO, heads[branch], MIGRATION)
    if not rules:
        sys.exit('ERROR: no branch of %s has %s with its checks' % (REPO, MIGRATION))
    defaults, defaults_from = migration_defaults(master_sha)

    releases = []
    for sha, ref in common.ls_remote(REPO + '.git', 'v*', kind='--tags'):
        t = re.fullmatch(r'refs/tags/v(\d+)\.(\d+)\.(\d+)', ref)
        if t:
            releases.append((tuple(int(x) for x in t.groups()), ref[len('refs/tags/'):]))
    if not releases:
        sys.exit('ERROR: %s has no release tag vX.Y.Z' % REPO)
    newest_version, newest_tag = max(releases)

    schedule = common.fetch(SCHEDULE)
    wiki_sha = common.ls_remote(WIKI, 'HEAD', kind='')[0][0]
    maintained = sorted(schedule_majors(schedule, '## Currently supported versions'))
    eol = schedule_majors(schedule, '## EOL Versions')
    if not maintained or not eol:
        sys.exit('ERROR: the schedule lists no supported or no end-of-life major; has its layout changed?')

    values = {
        'master': master,
        'newest': newest_version[0],
        'maintained': maintained,
        'eol': max(eol),
        'php': php,
        'extensions': ext,
        'root_urls': roots,
        'migrations': {'rules': rules, **defaults},
    }
    if not (values['eol'] < maintained[0] <= values['newest'] < master):
        sys.exit('ERROR: the sources disagree: %r' % {k: v for k, v in values.items() if k not in ('php', 'extensions', 'root_urls', 'migrations')})
    sources = {
        'master': '%s/blob/%s/version.php' % (REPO, master_sha),
        'newest': '%s/releases/tag/%s' % (REPO, newest_tag),
        'schedule': '%s/wiki/Maintenance-and-Release-Schedule/%s' % (REPO, wiki_sha),
        'php': {k: '%s/blob/%s/lib/versioncheck.php' % (REPO, b['commit']) for k, b in branches.items()},
        'extensions': ext_from,
        'root_urls': roots_from,
        'migrations': {'rules': rules_from, **defaults_from},
    }
    common.write('nextcloud-server', ABOUT, sources, values)


main()
