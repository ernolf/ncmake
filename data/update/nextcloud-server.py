# data/nextcloud-server.json: the majors of nextcloud/server and the PHP each one
# runs on.
#
#   master      the major in development, $OC_Version of version.php on master
#   newest      the highest major among the release tags vX.Y.Z; a tag with a
#               beta or rc suffix is no release
#   maintained  the majors under "Currently supported versions" of the server's
#               Maintenance and Release Schedule
#   eol         the newest major under "EOL Versions" of that page
#   php         per major, the PHP minors lib/versioncheck.php of its stable
#               branch, or of master for the major in development, lets the
#               server run on: it refuses PHP_VERSION_ID < floor and >= the minor
#               after the ceiling. A branch whose versioncheck.php states neither
#               is left out.

import re
import sys

import common

REPO = 'https://github.com/nextcloud/server'
RAW = 'https://raw.githubusercontent.com/nextcloud/server'
WIKI = 'https://github.com/nextcloud/server.wiki.git'
SCHEDULE = 'https://raw.githubusercontent.com/wiki/nextcloud/server/Maintenance-and-Release-Schedule.md'

ABOUT = ('The majors of nextcloud/server and the PHP each one runs on, generated by '
         'data/update/nextcloud-server.py from the sources it names. Not edited by hand.')


def minor(version_id):
    return '%d.%d' % (version_id // 10000, version_id % 10000 // 100)


def php_range(text):
    floor = re.search(r'PHP_VERSION_ID\s*<\s*(\d+)', text)
    above = re.search(r'PHP_VERSION_ID\s*>=\s*(\d+)', text)
    r = {}
    if floor:
        r['min'] = minor(int(floor.group(1)))
    if above:
        r['max'] = minor(int(above.group(1)) - 100)
    return r


def schedule_majors(text, heading):
    """The majors in the bold first column of the table below heading."""
    majors = []
    inside = False
    for line in text.splitlines():
        if line.startswith('## '):
            inside = line.strip() == heading
            continue
        m = inside and re.match(r'^\|\s*\*\*(\d+)\*\*', line)
        if m:
            majors.append(int(m.group(1)))
    return majors


def main():
    heads = {ref[len('refs/heads/'):]: sha for sha, ref in common.ls_remote(REPO + '.git', 'master', 'stable*')}
    master_sha = heads.get('master')
    if not master_sha:
        sys.exit('ERROR: %s has no branch master' % REPO)
    version = common.fetch('%s/%s/version.php' % (RAW, master_sha))
    m = re.search(r'^\$OC_Version\s*=\s*\[\s*(\d+)', version, re.M)
    if not m:
        sys.exit('ERROR: no $OC_Version in version.php of master')
    master = int(m.group(1))

    php = {}
    branches = {}
    stable = sorted((int(b[len('stable'):]), b) for b in heads if re.fullmatch(r'stable\d+', b))
    for major, branch in stable + [(master, 'master')]:
        text = common.fetch('%s/%s/lib/versioncheck.php' % (RAW, heads[branch]), missing_ok=True)
        r = php_range(text or '')
        if r:
            php[str(major)] = r
            branches[str(major)] = {'branch': branch, 'commit': heads[branch]}

    releases = []
    for sha, ref in common.ls_remote(REPO + '.git', 'v*', kind='--tags'):
        t = re.fullmatch(r'refs/tags/v(\d+)\.(\d+)\.(\d+)', ref)
        if t:
            releases.append((tuple(int(x) for x in t.groups()), ref[len('refs/tags/'):]))
    if not releases:
        sys.exit('ERROR: %s has no release tag vX.Y.Z' % REPO)
    newest_version, newest_tag = max(releases)

    schedule = common.fetch(SCHEDULE)
    wiki_sha = common.ls_remote(WIKI, 'HEAD', kind='')[0][0]
    maintained = sorted(schedule_majors(schedule, '## Currently supported versions'))
    eol = schedule_majors(schedule, '## EOL Versions')
    if not maintained or not eol:
        sys.exit('ERROR: the schedule lists no supported or no end-of-life major; has its layout changed?')

    values = {
        'master': master,
        'newest': newest_version[0],
        'maintained': maintained,
        'eol': max(eol),
        'php': php,
    }
    if not (values['eol'] < maintained[0] <= values['newest'] < master):
        sys.exit('ERROR: the sources disagree: %r' % {k: v for k, v in values.items() if k != 'php'})
    sources = {
        'master': '%s/blob/%s/version.php' % (REPO, master_sha),
        'newest': '%s/releases/tag/%s' % (REPO, newest_tag),
        'schedule': '%s/wiki/Maintenance-and-Release-Schedule/%s' % (REPO, wiki_sha),
        'php': {k: '%s/blob/%s/lib/versioncheck.php' % (REPO, b['commit']) for k, b in branches.items()},
    }
    common.write('nextcloud-server', ABOUT, sources, values)


main()
