# data/nextcloud-eslint.json: the globals the Nextcloud server and its build
# configuration provide to the scripts of an app.
#
#   globals  each global with readonly or writable, as the released
#            @nextcloud/eslint-config declares it in lib/configs/javascript.ts;
#            the spread sets of the globals package are left out

import json
import re
import sys

import common

PACKAGE = '@nextcloud/eslint-config'
REGISTRY = 'https://registry.npmjs.org/@nextcloud%2Feslint-config/latest'
REPO = 'https://github.com/nextcloud-libraries/eslint-config'
RAW = 'https://raw.githubusercontent.com/nextcloud-libraries/eslint-config'
CONFIG = 'lib/configs/javascript.ts'

ABOUT = ('The globals the Nextcloud server provides to the scripts of an app, generated by '
         'data/update/nextcloud-eslint.py from the sources it names. Not edited by hand.')


def nextcloud_globals(text):
    m = re.search(r'^(\s*)globals:\s*\{\n(.*?)^\1\},', text, re.M | re.S)
    if not m:
        sys.exit('ERROR: %s has no globals block' % CONFIG)
    return dict(re.findall(r"^\s*([A-Za-z_$][\w$]*):\s*'(readonly|writable|off)',?\s*$", m.group(2), re.M))


def main():
    latest = json.loads(common.fetch(REGISTRY))
    commit = latest.get('gitHead')
    if not commit:
        sys.exit('ERROR: %s %s names no gitHead' % (PACKAGE, latest.get('version')))
    values = {'globals': nextcloud_globals(common.fetch('%s/%s/%s' % (RAW, commit, CONFIG)))}
    if not values['globals']:
        sys.exit('ERROR: no global was read from %s; has its layout changed?' % CONFIG)
    sources = {
        'globals': '%s/blob/%s/%s' % (REPO, commit, CONFIG),
        'release': 'https://www.npmjs.com/package/%s/v/%s' % (PACKAGE, latest['version']),
    }
    common.write('nextcloud-eslint', ABOUT, sources, values)


main()
