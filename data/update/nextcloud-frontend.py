# data/nextcloud-frontend.json: the globals the Nextcloud server sets for the
# scripts of an app, per major, read from core/src/globals.js and
# core/src/OC/index.js of nextcloud/server on each stable branch and master.
#
#   majors   the majors read: one per branch stable<major> that has the files,
#            and the one after the highest for master
#   globals  per global the server sets on window from a package (t, n, ...):
#              majors      the first and the last major that sets it so
#              package     the @nextcloud package of the newest of them
#   oc       per member of OC:
#              majors      the first and the last major that has it
#              package     the @nextcloud package the newest of them takes
#                          it from, or null
#              deprecated  [major, text] of its @deprecated tag: the major
#                          the tag names, else the first major read that has
#                          it, and the text of the newest without the version
#                          that starts it; or null

import re
import sys

import common

REPO = 'https://github.com/nextcloud/server'
RAW = 'https://raw.githubusercontent.com/nextcloud/server'
GLOBALS = 'core/src/globals.js'
OC = 'core/src/OC/index.js'

ABOUT = ('The globals the Nextcloud server sets for the scripts of an app, per major, with the @nextcloud package '
         'each comes from and its deprecation, generated by data/update/nextcloud-frontend.py from the sources it '
         'names. Not edited by hand.')

NAME = r'[A-Za-z_$][\w$]*'
IMPORT = re.compile(r'^import\s+(?:(%s)\s*,?\s*)?(?:\{([^}]*)\})?\s*from\s+[\'"](@nextcloud/[^\'"]+)[\'"]' % NAME, re.M)
WINDOW = re.compile(r'^window\.(%s)\s*=\s*(%s)\s*$' % (NAME, NAME), re.M)
OBJECT = re.compile(r'^export default \{\n(.*?)^\}', re.M | re.S)
ENTRY = re.compile(r'^\t(%s)\s*(?::\s*([^\n]*?))?,?$' % NAME)
DEPRECATED = re.compile(r'@deprecated\b((?:(?!\n\s*\*?\s*@).)*)', re.S)
VERSION = re.compile(r'^\s*-?\s*v?\d+(?:\.\d+)*\s*[-:,]?\s*')


def imports(text):
    """{local name: package} of the @nextcloud packages a file imports."""
    out = {}
    for default, names, package in IMPORT.findall(text):
        if default:
            out[default] = package
        for part in names.split(','):
            words = part.split()
            if words:
                out[words[-1]] = package
    return out


def deprecation(doc):
    tag = DEPRECATED.search(doc)
    if not tag:
        return None
    text = ' '.join(line.strip().lstrip('*').strip() for line in tag.group(1).splitlines()).strip()
    version = VERSION.match(text)
    major = int(re.match(r'\D*(\d+)', version.group(0)).group(1)) if version else None
    return major, VERSION.sub('', text, count=1).strip()


def oc_members(text):
    """{member: (package or None, deprecation text or None)} of the object
    core/src/OC/index.js exports."""
    obj = OBJECT.search(text)
    if not obj:
        sys.exit('ERROR: %s exports no object; has its layout changed?' % OC)
    imported = imports(text)
    out = {}
    lines = obj.group(1).split('\n')
    for i, line in enumerate(lines):
        m = ENTRY.match(line)
        if not m:
            continue
        name, value = m.group(1), (m.group(2) or m.group(1)).strip()
        # The doc comment that ends right above the member, and no other.
        before = '\n'.join(lines[:i]).rstrip()
        start = before.rfind('/**')
        doc = before[start + 3:-2] if before.endswith('*/') and start >= 0 and '*/' not in before[start:-2] else ''
        dep = deprecation(doc)
        out[name] = (imported.get(value) if re.fullmatch(NAME, value) else None, dep)
    if not out:
        sys.exit('ERROR: no member was read from %s; has its layout changed?' % OC)
    return out


def main():
    heads = {ref: sha for sha, ref in common.ls_remote(REPO, 'refs/heads/stable*', 'refs/heads/master')}
    stable = sorted(int(m.group(1)) for m in (re.fullmatch(r'refs/heads/stable(\d+)', r) for r in heads) if m)
    if not stable or 'refs/heads/master' not in heads:
        sys.exit('ERROR: %s has no stable branch or no master' % REPO)
    refs = {major: 'refs/heads/stable%d' % major for major in stable}
    refs[stable[-1] + 1] = 'refs/heads/master'
    values = {'majors': [], 'globals': {}, 'oc': {}}
    sources = {}
    for major, ref in sorted(refs.items()):
        sha = heads[ref]
        oc = common.fetch('%s/%s/%s' % (RAW, sha, OC), missing_ok=True)
        glob = common.fetch('%s/%s/%s' % (RAW, sha, GLOBALS), missing_ok=True)
        if oc is None or glob is None:
            continue
        values['majors'].append(major)
        sources[str(major)] = '%s/tree/%s' % (REPO, sha)
        imported = imports(glob)
        for name, value in WINDOW.findall(glob):
            if value in imported:
                g = values['globals'].setdefault(name, {'majors': [major, major]})
                g['majors'][1] = major
                g['package'] = imported[value]
        for name, (package, dep) in oc_members(oc).items():
            o = values['oc'].setdefault(name, {'majors': [major, major], 'package': None, 'deprecated': None})
            o['majors'][1] = major
            o['package'] = package
            if dep is not None:
                since = dep[0] or (o['deprecated'][0] if o['deprecated'] else major)
                o['deprecated'] = [since, dep[1]]
            else:
                o['deprecated'] = None
    if not values['majors']:
        sys.exit('ERROR: no branch of %s has %s and %s' % (REPO, OC, GLOBALS))
    values['globals'] = dict(sorted(values['globals'].items()))
    values['oc'] = dict(sorted(values['oc'].items()))
    common.write('nextcloud-frontend', ABOUT, sources, values)


main()
