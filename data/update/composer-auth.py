# data/composer-auth.json: the keys of the auth.json of composer that hold a
# credential.
#
#   keys  the keys composer writes into a new global auth.json, in
#         src/Composer/Command/ConfigCommand.php of its latest release; the schema,
#         res/composer-schema.json, describes them like any other config object
#         and does not tell them apart

import json
import re
import sys

import common

REPO = 'https://github.com/composer/composer'
LATEST = 'https://api.github.com/repos/composer/composer/releases/latest'
RAW = 'https://raw.githubusercontent.com/composer/composer'
SOURCE = 'src/Composer/Command/ConfigCommand.php'

ABOUT = ('The keys of the auth.json of composer that hold a credential, generated by '
         'data/update/composer-auth.py from the sources it names. Not edited by hand.')


def main():
    tag = json.loads(common.fetch(LATEST))['tag_name']
    m = re.search(r'authConfigFile->write\(\[(.*?)\]\);', common.fetch('%s/%s/%s' % (RAW, tag, SOURCE)))
    keys = re.findall(r"'([a-z-]+)' => new \\ArrayObject", m.group(1)) if m else []
    if not keys:
        sys.exit('ERROR: no auth.json key was read from %s at %s; has its layout changed?' % (SOURCE, tag))
    common.write('composer-auth', ABOUT, {'keys': '%s/blob/%s/%s' % (REPO, tag, SOURCE)}, {'keys': keys})


main()
