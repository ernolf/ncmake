# data/spdx-licenses.json: the licence ids and the exception ids of the SPDX
# license list.
#
#   ids         every licenseId of json/licenses.json in the latest release of
#               spdx/license-list-data, deprecated ones included, as SPDX keeps
#               those
#   deprecated  the ids of ids that SPDX marks as deprecated
#   exceptions  every licenseExceptionId of json/exceptions.json in the same
#               release that is not deprecated
#
# The licence table of deps-audit, lib/licences.json, is written by hand; its
# self-test holds every id it names against this list. consistency-audit takes
# the current ids, and the exceptions a WITH names, as SPDX ids.

import json
import sys

import common

REPO = 'https://github.com/spdx/license-list-data'
LATEST = 'https://api.github.com/repos/spdx/license-list-data/releases/latest'
RAW = 'https://raw.githubusercontent.com/spdx/license-list-data'
LIST = 'json/licenses.json'
EXCEPTIONS = 'json/exceptions.json'

ABOUT = ('The licence ids and the exception ids of the SPDX license list, generated by '
         'data/update/spdx-licenses.py from the sources it names. Not edited by hand.')


def main():
    tag = json.loads(common.fetch(LATEST))['tag_name']
    licences = json.loads(common.fetch('%s/%s/%s' % (RAW, tag, LIST)))['licenses']
    ids = sorted((l['licenseId'] for l in licences), key=str.lower)
    if not ids:
        sys.exit('ERROR: %s at %s lists no licence' % (LIST, tag))
    deprecated = sorted((l['licenseId'] for l in licences if l['isDeprecatedLicenseId']), key=str.lower)
    exceptions = sorted((e['licenseExceptionId'] for e in json.loads(common.fetch('%s/%s/%s' % (RAW, tag, EXCEPTIONS)))['exceptions']
                         if not e['isDeprecatedLicenseId']), key=str.lower)
    if not exceptions:
        sys.exit('ERROR: %s at %s lists no exception' % (EXCEPTIONS, tag))
    blob = '%s/blob/%s/%%s' % (REPO, tag)
    common.write('spdx-licenses', ABOUT, {'ids': blob % LIST, 'deprecated': blob % LIST, 'exceptions': blob % EXCEPTIONS},
                 {'ids': ids, 'deprecated': deprecated, 'exceptions': exceptions})


main()
