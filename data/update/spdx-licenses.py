# data/spdx-licenses.json: the licence ids of the SPDX license list.
#
#   ids  every licenseId of json/licenses.json in the latest release of
#        spdx/license-list-data, deprecated ones included, as SPDX keeps those
#
# The licence table of deps-audit, lib/licences.json, is written by hand; its
# self-test holds every id it names against this list.

import json
import sys

import common

REPO = 'https://github.com/spdx/license-list-data'
LATEST = 'https://api.github.com/repos/spdx/license-list-data/releases/latest'
RAW = 'https://raw.githubusercontent.com/spdx/license-list-data'
LIST = 'json/licenses.json'

ABOUT = ('The licence ids of the SPDX license list, generated by '
         'data/update/spdx-licenses.py from the sources it names. Not edited by hand.')


def main():
    tag = json.loads(common.fetch(LATEST))['tag_name']
    ids = sorted((l['licenseId'] for l in json.loads(common.fetch('%s/%s/%s' % (RAW, tag, LIST)))['licenses']), key=str.lower)
    if not ids:
        sys.exit('ERROR: %s at %s lists no licence' % (LIST, tag))
    common.write('spdx-licenses', ABOUT, {'ids': '%s/blob/%s/%s' % (REPO, tag, LIST)}, {'ids': ids})


main()
