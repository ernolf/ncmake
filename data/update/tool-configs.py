# data/tool-configs.json: the names of the configuration files each tool finds in
# the directory it runs in, in the order it tries them, as its own source lists
# them.
#
#   <tool>.files         the file names of the current form
#   eslint.legacy        the eslintrc file names, which ESLint 9 and newer no
#                        longer read, and eslint.legacyPkgKey, their key in
#                        package.json
#   stylelint.pkgKey     the key in package.json stylelint also reads
#
# The lint targets name the configuration a run went by and fall back to their
# own default where an app has none; consistency-audit reports a tool without its
# configuration. A tool that adds or renames a file name changes this list, not
# the analysers. The tools make pins are read at the release data/tools.json
# names, the PHP tools at their latest release.

import json
import os
import re
import sys

import common

TOOLS = os.path.join(common.DATA_DIR, 'tools.json')

ABOUT = ('The configuration file names of each tool the lint targets and consistency-audit '
         'look for, generated by data/update/tool-configs.py from the sources it names. '
         'Not edited by hand.')


def pinned(name):
    with open(TOOLS, 'r', encoding='utf-8') as f:
        version = json.load(f)['values'].get(name, {}).get('version')
    if not version:
        sys.exit('ERROR: data/tools.json names no %s version' % name)
    return version


def latest(repo):
    return json.loads(common.fetch('https://api.github.com/repos/%s/releases/latest' % repo))['tag_name']


def source(repo, tag, path):
    """(text, blob url) of path in repo at tag."""
    text = common.fetch('https://raw.githubusercontent.com/%s/%s/%s' % (repo, tag, path))
    return text, 'https://github.com/%s/blob/%s/%s' % (repo, tag, path)


def strings(block):
    return re.findall(r'''["']([^"']+)["']''', block)


def between(text, start, where):
    """The string literals of the list that the regex start opens, up to its
    closing bracket."""
    m = re.search(start + r'(.*?)\]', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no list at %r; has its layout changed?' % (where, start))
    return m.group(1)


def caret(rng, versions, where):
    """The highest release of versions that the caret range rng allows."""
    m = re.fullmatch(r'\^(\d+)\.(\d+)\.(\d+)', rng)
    if not m:
        sys.exit('ERROR: %s requires cosmiconfig %s, which is not a caret range' % (where, rng))
    low = tuple(int(x) for x in m.groups())
    ok = [v for v in versions if re.fullmatch(r'\d+\.\d+\.\d+', v)
          and int(v.split('.')[0]) == low[0] and tuple(int(x) for x in v.split('.')) >= low]
    if not ok:
        sys.exit('ERROR: no release of cosmiconfig meets %s' % rng)
    return max(ok, key=lambda v: tuple(int(x) for x in v.split('.')))


def main():
    values, sources = {}, {}

    tag = 'v' + pinned('actionlint')
    text, sources['actionlint'] = source('rhysd/actionlint', tag, 'config.go')
    m = re.search(r'func loadRepoConfig\(.*?range \[\]string\{([^}]*)\}.*?filepath\.Join\(root, "([^"]+)", f\)', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no file list in loadRepoConfig; has its layout changed?' % sources['actionlint'])
    values['actionlint'] = {'files': ['%s/%s' % (m.group(2), f) for f in strings(m.group(1))]}

    # shellcheck tries each name in the directory of a script and then in every
    # directory above it.
    tag = 'v' + pinned('shellcheck')
    text, sources['shellcheck'] = source('koalaman/shellcheck', tag, 'shellcheck.hs')
    m = re.search(r'getConfigPaths dir = do.*?return \$ ((?:\(dir </> "[^"]+"\) : )+)rest', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no file list in getConfigPaths; has its layout changed?' % sources['shellcheck'])
    values['shellcheck'] = {'files': strings(m.group(1))}

    tag = 'v' + pinned('zizmor')
    text, sources['zizmor'] = source('zizmorcore/zizmor', tag, 'crates/zizmor/src/config/mod.rs')
    values['zizmor'] = {'files': strings(between(text, r'const CONFIG_CANDIDATES: &\[&str\] = &\[', sources['zizmor']))}

    tag = 'v' + pinned('hadolint')
    text, sources['hadolint'] = source('hadolint/hadolint', tag, 'src/Hadolint/Config/Configfile.hs')
    # The working directory is searched for hiddenConfigs; the other lists are
    # for the directories of the user.
    if not re.search(r'getCurrentDirectory\)\s*hiddenConfigs', text):
        sys.exit('ERROR: %s does not search the working directory for hiddenConfigs; has its layout changed?' % sources['hadolint'])
    values['hadolint'] = {'files': strings(between(text, r'hiddenConfigs = \[', sources['hadolint']))}

    tag = 'v' + pinned('yamllint')
    text, sources['yamllint'] = source('adrienverge/yamllint', tag, 'yamllint/cli.py')
    m = re.search(r'def find_project_config_filepath\(.*?\n\s+for filename in \(([^)]*)\):', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no file list in find_project_config_filepath; has its layout changed?' % sources['yamllint'])
    values['yamllint'] = {'files': strings(m.group(1))}

    tag = 'v' + pinned('markdownlint-cli2')
    text, sources['markdownlint-cli2'] = source('DavidAnson/markdownlint-cli2', tag, 'markdownlint-cli2.mjs')
    # Each entry is [ name, handler ]; the options files come before the
    # configuration files, as the order in which a directory is read.
    files = []
    for name in ('optionsFiles', 'configurationFiles'):
        m = re.search(r'const %s = \[(.*?)\n\];' % name, text, re.S)
        if not m:
            sys.exit('ERROR: %s holds no %s; has its layout changed?' % (sources['markdownlint-cli2'], name))
        files += re.findall(r'\[\s*"([^"]+)"\s*,', m.group(1))
    values['markdownlint-cli2'] = {'files': files}

    tag = 'v' + pinned('eslint')
    text, sources['eslint'] = source('eslint/eslint', tag, 'lib/config/config-loader.js')
    flat = strings(between(text, r'const FLAT_CONFIG_FILENAMES = \[', sources['eslint']))
    # The eslintrc form lives in @eslint/eslintrc, which ESLint 9 dropped; its
    # latest release is the last word on the names it reads.
    version = json.loads(common.fetch('https://registry.npmjs.org/@eslint/eslintrc/latest'))['version']
    text, sources['eslintrc'] = source('eslint/eslintrc', 'eslintrc-v' + version, 'lib/config-array-factory.js')
    legacy = strings(between(text, r'const configFilenames = \[', sources['eslintrc']))
    key = re.search(r'Object\.hasOwn\(packageData, "([^"]+)"\)', text)
    if 'package.json' not in legacy or not key:
        sys.exit('ERROR: %s reads no key of package.json; has its layout changed?' % sources['eslintrc'])
    values['eslint'] = {'files': flat, 'legacy': [f for f in legacy if f != 'package.json'], 'legacyPkgKey': key.group(1)}

    # stylelint hands its module name to cosmiconfig and nothing else that decides
    # where to look, so the search places are cosmiconfig's defaults for that name,
    # package.json under the same name as its key.
    tag = pinned('stylelint')
    text, sources['stylelint'] = source('stylelint/stylelint', tag, 'lib/createStylelint.mjs')
    m = re.search(r"_configExplorer: cosmiconfig\('([^']+)', \{(.*?)\}\)", text, re.S)
    if not m or re.search(r'searchPlaces|packageProp', m.group(2)):
        sys.exit('ERROR: %s does not hand cosmiconfig its defaults; has its layout changed?' % sources['stylelint'])
    module = m.group(1)
    rng = json.loads(common.fetch('https://raw.githubusercontent.com/stylelint/stylelint/%s/package.json' % tag))['dependencies']['cosmiconfig']
    version = caret(rng, json.loads(common.fetch('https://registry.npmjs.org/cosmiconfig'))['versions'], sources['stylelint'])
    text, sources['cosmiconfig'] = source('cosmiconfig/cosmiconfig', 'v' + version, 'src/defaults.ts')
    m = re.search(r'export function getDefaultSearchPlaces\(moduleName: string\): Array<string> \{\s*return \[(.*?)\];', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no getDefaultSearchPlaces; has its layout changed?' % sources['cosmiconfig'])
    places = [p.replace('${moduleName}', module) for p in re.findall(r"""['`]([^'`]+)['`]""", m.group(1))]
    if 'package.json' not in places:
        sys.exit('ERROR: %s does not search package.json; has its layout changed?' % sources['cosmiconfig'])
    values['stylelint'] = {'files': [p for p in places if p != 'package.json'], 'pkgKey': module}

    # html-validate lives on GitLab. Its CLI looks for a flat config first and
    # only without one for the .htmlvalidate files.
    tag = 'v' + pinned('html-validate')
    gitlab = 'https://gitlab.com/html-validate/html-validate/-/%s/' + tag + '/%s'
    path = 'src/flat-config/find-flat-config-file.nodejs.ts'
    text = common.fetch(gitlab % ('raw', path))
    sources['html-validate'] = gitlab % ('blob', path)
    files = strings(between(text, r'const FLAT_CONFIG_FILES = \[', sources['html-validate']))
    path = 'src/config/loaders/file-system.ts'
    text = common.fetch(gitlab % ('raw', path))
    sources['html-validate-rc'] = gitlab % ('blob', path)
    m = re.search(r'function findConfigurationFiles\(.*?return \[([^\]]*)\]\s*\.map\(\(extension\) => path\.join\(directory, `([^`$]*)\$\{extension\}`\)\)', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no file list in findConfigurationFiles; has its layout changed?' % sources['html-validate-rc'])
    values['html-validate'] = {'files': files + [m.group(2) + e for e in strings(m.group(1))]}

    text, sources['psalm'] = source('vimeo/psalm', latest('vimeo/psalm'), 'src/Psalm/Config.php')
    values['psalm'] = {'files': strings(between(text, r'const DEFAULT_FILE_NAMES = \[', sources['psalm']))}

    text, sources['phpunit'] = source('sebastianbergmann/phpunit', latest('sebastianbergmann/phpunit'),
                                      'src/TextUI/Configuration/Cli/XmlConfigurationFileFinder.php')
    m = re.search(r'function configurationFileInDirectory\(.*?\$candidates = \[(.*?)\]', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no candidates in configurationFileInDirectory; has its layout changed?' % sources['phpunit'])
    values['phpunit'] = {'files': re.findall(r"\$directory \. '/([^']+)'", m.group(1))}

    text, sources['php-cs-fixer'] = source('PHP-CS-Fixer/PHP-CS-Fixer', latest('PHP-CS-Fixer/PHP-CS-Fixer'),
                                           'src/Console/ConfigurationResolver.php')
    m = re.search(r'\$candidates = \[(.*?)\]', text, re.S)
    if not m:
        sys.exit('ERROR: %s holds no candidates; has its layout changed?' % sources['php-cs-fixer'])
    # The v2 names are there only to fail with a message.
    values['php-cs-fixer'] = {'files': [n for n, rest in re.findall(r"DIRECTORY_SEPARATOR\.'([^']+)',([^\n]*)", m.group(1))
                                        if 'old v2 config' not in rest]}

    for tool, v in values.items():
        if not v['files']:
            sys.exit('ERROR: no configuration file name of %s found; has the layout of its source changed?' % tool)
    common.write('tool-configs', ABOUT, sources, values)


main()
