# data/zizmor-audits.json: the audits of the zizmor release lint-actions-security
# runs.
#
#   audits  the id of every audit docs/audits.md documents at the release
#           data/tools.json names, in the order of the page
#
# lint-actions-security sorts each audit into attack or hardening; its self-test
# holds that table against this list, so an audit zizmor adds, renames or drops
# is noticed.

import json
import os
import re
import sys

import common

REPO = 'https://github.com/zizmorcore/zizmor'
RAW = 'https://raw.githubusercontent.com/zizmorcore/zizmor'
DOCS = 'docs/audits.md'
MODULES = 'crates/zizmor/src/audit/mod.rs'
TOOLS = os.path.join(common.DATA_DIR, 'tools.json')

ABOUT = ('The audit ids of the zizmor release lint-actions-security runs, generated by '
         'data/update/zizmor-audits.py from the sources it names. Not edited by hand.')


def main():
    with open(TOOLS, 'r', encoding='utf-8') as f:
        version = json.load(f)['values'].get('zizmor', {}).get('version')
    if not version:
        sys.exit('ERROR: data/tools.json names no zizmor version')
    tag = 'v' + version
    audits = re.findall(r'^## `([a-z0-9-]+)`\s*$', common.fetch('%s/%s/%s' % (RAW, tag, DOCS)), re.M)
    # Each audit is a module of the audit crate; a page that documents another
    # set means its layout has changed.
    modules = re.findall(r'^pub\(crate\) mod (\w+);', common.fetch('%s/%s/%s' % (RAW, tag, MODULES)), re.M)
    if not audits or sorted(audits) != sorted(m.replace('_', '-') for m in modules):
        sys.exit('ERROR: the audits of %s at %s are not the modules of %s; has its layout changed?' % (DOCS, tag, MODULES))
    common.write('zizmor-audits', ABOUT, {'audits': '%s/blob/%s/%s' % (REPO, tag, DOCS)}, {'audits': audits})


main()
