# data/tools.json: the newest release of every tool the lint and audit modules
# fetch, with what a fetch checks it against. One entry per tool:
#
#   <binary>   the latest release of its GitHub repository: version, and per
#              architecture the download URL of the asset with the Linux build and
#              the sha256 digest GitHub publishes for it
#   <python>   the newest version on PyPI: version, the path of its source
#              distribution below packages/source/ of files.pythonhosted.org and
#              the sha256 PyPI publishes for it
#   <npm>      the version the latest tag of the npm registry names
#   <composer> the newest stable version on Packagist: version, the commit of
#              its source repository Packagist records for it, and the URL of
#              that commit as a tarball
#
# The packages yamllint imports are the ones its newest release requires. They are
# fetched as source distributions without pip, so a release that requires another
# one stops this script instead of shipping an import that fails. So does a
# package whose newest version is outside the range a peer of its npm group
# accepts, as npm would refuse the install.
#
# The Composer package is fetched as the tree of the commit Packagist names, as
# Composer installs a package from GitHub: the commit is the identity, and no
# digest of the archive exists, since GitHub packs it on request.

import json
import re
import sys

import common

GITHUB = 'https://api.github.com/repos'
PYPI = 'https://pypi.org/pypi'
NPM = 'https://registry.npmjs.org'
PACKAGIST = 'https://repo.packagist.org/p2'

# The asset of the Linux build per architecture, with {v} for the version.
BINARIES = {
    'actionlint': ('rhysd/actionlint', 'actionlint_{v}_linux_amd64.tar.gz', 'actionlint_{v}_linux_arm64.tar.gz'),
    'gitleaks': ('gitleaks/gitleaks', 'gitleaks_{v}_linux_x64.tar.gz', 'gitleaks_{v}_linux_arm64.tar.gz'),
    'hadolint': ('hadolint/hadolint', 'hadolint-linux-x86_64', 'hadolint-linux-arm64'),
    'shellcheck': ('koalaman/shellcheck', 'shellcheck-v{v}.linux.x86_64.tar.gz', 'shellcheck-v{v}.linux.aarch64.tar.gz'),
    'zizmor': ('zizmorcore/zizmor', 'zizmor-x86_64-unknown-linux-gnu.tar.gz', 'zizmor-aarch64-unknown-linux-gnu.tar.gz'),
}
PYTHON = 'yamllint'
PYTHON_DEPS = {'pathspec', 'pyyaml'}
# Installed together, so the peers of each group are held against each other.
NPM_GROUPS = [
    ['markdownlint-cli2'],
    ['eslint', '@eslint/js', 'globals', 'stylelint', 'stylelint-config-standard', 'html-validate'],
]
# Read by lib/php-audit.php through an autoloader of its own: the package has no
# dependency but extensions every PHP image has.
COMPOSER = {'php-parser': 'nikic/php-parser'}

ABOUT = ('The newest release of each tool the lint and audit modules fetch, with the digests a fetch '
         'checks, generated by data/update/tools.py from the sources it names. Not edited by hand.')


def binary(repo, x86_64, aarch64):
    rel = json.loads(common.fetch('%s/%s/releases/latest' % (GITHUB, repo)))
    version = rel['tag_name'].removeprefix('v')
    assets = {a['name']: a for a in rel['assets']}
    entry = {'version': version}
    for arch, pattern in (('x86_64', x86_64), ('aarch64', aarch64)):
        name = pattern.format(v=version)
        if name not in assets:
            sys.exit('ERROR: %s %s has no asset %s' % (repo, rel['tag_name'], name))
        digest = assets[name].get('digest') or ''
        if not digest.startswith('sha256:'):
            sys.exit('ERROR: GitHub publishes no sha256 digest for %s of %s %s' % (name, repo, rel['tag_name']))
        entry[arch] = {'url': assets[name]['browser_download_url'], 'sha256': digest.removeprefix('sha256:')}
    return entry, rel['html_url']


def normalized(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def python(project):
    doc = json.loads(common.fetch('%s/%s/json' % (PYPI, project)))
    version = doc['info']['version']
    sdists = [u for u in doc['urls'] if u['packagetype'] == 'sdist']
    if len(sdists) != 1:
        sys.exit('ERROR: %s %s has %d source distributions on PyPI, not one' % (project, version, len(sdists)))
    name = normalized(project)
    entry = {'version': version, 'path': '%s/%s/%s' % (name[0], name, sdists[0]['filename']),
             'sha256': sdists[0]['digests']['sha256']}
    return entry, doc['info']['requires_dist'] or [], 'https://pypi.org/project/%s/%s/' % (project, version)


def requirement(spec):
    """The project a requires_dist entry names, or None for one behind an extra."""
    req, _, marker = spec.partition(';')
    if 'extra' in marker:
        return None
    return normalized(re.match(r'\s*([A-Za-z0-9._-]+)', req).group(1))


def composer(package):
    doc = json.loads(common.fetch('%s/%s.json' % (PACKAGIST, package)))
    # Packagist lists the versions newest first, each as what differs from the
    # one before it.
    full = {}
    for entry in doc['packages'][package]:
        for key, value in entry.items():
            if value == '__unset':
                full.pop(key, None)
            else:
                full[key] = value
        if re.fullmatch(r'v?\d+(\.\d+)*', full['version']):
            break
    else:
        sys.exit('ERROR: Packagist names no stable version of %s' % package)
    source = full.get('source') or {}
    m = re.fullmatch(r'https://github\.com/([^/]+/[^/]+?)(?:\.git)?', source.get('url') or '')
    if source.get('type') != 'git' or not m or not re.fullmatch(r'[0-9a-f]{40}', source.get('reference') or ''):
        sys.exit('ERROR: %s %s has no commit of a GitHub repository as its source' % (package, full['version']))
    version = full['version'].removeprefix('v')
    entry = {'version': version, 'commit': source['reference'],
             'url': 'https://codeload.github.com/%s/tar.gz/%s' % (m.group(1), source['reference'])}
    return entry, 'https://packagist.org/packages/%s#%s' % (package, full['version'])


def satisfies(version, spec):
    """Whether version is in an npm range of the forms peers use: alternatives
    joined by ||, each a list of ^, ~, comparison, exact and x-ranges."""
    have = tuple(int(n) for n in version.split('-')[0].split('.'))
    pad = lambda n: tuple((n + [0, 0, 0])[:3])
    up = lambda n: pad(n[:-1] + [n[-1] + 1]) if n else None

    def ok(op, text):
        m = re.fullmatch(r'v?((?:\d+|[xX*])(?:\.(?:\d+|[xX*])){0,2})(?:-[0-9A-Za-z.-]+)?', text)
        if not m:
            sys.exit('ERROR: cannot read the npm range %r' % spec)
        nums = []
        for part in m.group(1).split('.'):
            if not part.isdigit():
                break
            nums.append(int(part))
        low = pad(nums)
        if op == '^':
            nonzero = next((i for i, n in enumerate(nums) if n), len(nums) - 1)
            high = up(nums[:nonzero + 1])
        elif op == '~':
            high = up(nums[:2] if len(nums) > 2 else nums)
        elif op:
            return {'>=': have >= low, '>': have > low, '<=': have <= low, '<': have < low, '=': have == low}[op]
        elif len(nums) == 3:
            return have == low
        else:
            high = up(nums)
        return low <= have and (high is None or have < high)

    return any(all(ok(*re.fullmatch(r'(\^|~|>=|>|<=|<|=)?(.*)', c).groups()) for c in alt.split())
               for alt in spec.split('||'))


def main():
    values = {}
    sources = {}
    for tool, (repo, x86_64, aarch64) in BINARIES.items():
        values[tool], sources[tool] = binary(repo, x86_64, aarch64)

    values[PYTHON], requires, sources[PYTHON] = python(PYTHON)
    deps = {r for r in map(requirement, requires) if r}
    if deps != PYTHON_DEPS:
        sys.exit('ERROR: %s %s requires %s, while ncmake fetches %s' % (
            PYTHON, values[PYTHON]['version'], ', '.join(sorted(deps)), ', '.join(sorted(PYTHON_DEPS))))
    for dep in sorted(PYTHON_DEPS):
        values[dep], _, sources[dep] = python(dep)

    for group in NPM_GROUPS:
        docs = {p: json.loads(common.fetch('%s/%s/latest' % (NPM, p))) for p in group}
        for p, doc in docs.items():
            for peer, spec in (doc.get('peerDependencies') or {}).items():
                if peer in docs and not satisfies(docs[peer]['version'], spec):
                    sys.exit('ERROR: %s %s accepts %s %s, not the newest %s' % (
                        p, doc['version'], peer, spec, docs[peer]['version']))
            values[p] = {'version': doc['version']}
            sources[p] = 'https://www.npmjs.com/package/%s/v/%s' % (p, doc['version'])

    for tool, package in COMPOSER.items():
        values[tool], sources[tool] = composer(package)

    common.write('tools', ABOUT, sources, values)


main()
