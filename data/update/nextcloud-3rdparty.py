# data/nextcloud-3rdparty.json: the Composer packages the Nextcloud server ships
# in 3rdparty/, per major, read from composer.lock of the repository
# nextcloud/3rdparty at each branch stable<major> and at master.
#
#   majors    the majors read: one per branch stable<major> that has a
#             composer.lock, and the one after the highest for master
#   packages  per package of "packages" in a composer.lock, the majors that
#             ship it
#
# An app that ships one of them in its own vendor/ loads a second copy of a class
# the server already has, and which autoloader wins decides which version runs.

import json
import re
import sys

import common

REPO = 'https://github.com/nextcloud/3rdparty'
RAW = 'https://raw.githubusercontent.com/nextcloud/3rdparty/%s/composer.lock'

ABOUT = ('The Composer packages the Nextcloud server ships in 3rdparty/, with the majors that ship each, '
         'generated by data/update/nextcloud-3rdparty.py from the sources it names. Not edited by hand.')


def main():
    heads = {ref: sha for sha, ref in common.ls_remote(REPO, 'refs/heads/stable*', 'refs/heads/master')}
    stable = sorted(int(m.group(1)) for m in (re.fullmatch(r'refs/heads/stable(\d+)', r) for r in heads) if m)
    if not stable or 'refs/heads/master' not in heads:
        sys.exit('ERROR: %s has no stable branch or no master' % REPO)
    refs = {major: 'refs/heads/stable%d' % major for major in stable}
    refs[stable[-1] + 1] = 'refs/heads/master'

    majors, packages, sources = [], {}, {}
    for major in sorted(refs):
        sha = heads[refs[major]]
        text = common.fetch(RAW % sha, missing_ok=True)
        if text is None:
            continue
        majors.append(major)
        sources[str(major)] = '%s/blob/%s/composer.lock' % (REPO, sha)
        for package in json.loads(text).get('packages') or []:
            packages.setdefault(package['name'].lower(), []).append(major)
    if not packages:
        sys.exit('ERROR: no composer.lock of %s names a package' % REPO)
    values = {'majors': majors, 'packages': {name: packages[name] for name in sorted(packages)}}
    common.write('nextcloud-3rdparty', ABOUT, sources, values)


main()
